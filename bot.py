async def button(update: Update, ctx: ContextTypes.DEFAULT_TYPE):
    query = update.callback_query
    await query.answer()
    data = query.data

    # ── Language ──
    if data.startswith("lang_"):
        ctx.user_data["lang"] = data.split("_")[1]
        await query.edit_message_text(
            welcome_text(ctx),
            parse_mode="Markdown",
            reply_markup=paths_kb(ctx)
        )

    # ── Path selection ──
    elif data.startswith("path_"):
        path = int(data.split("_")[1])
        ctx.user_data["path"] = path

        if path == 0:  # подобрать практику
            await show_emotion_picker(query, ctx)

        elif path == 1:  # опора
            await show_category_practices(query, ctx, "🦶 Опора и заземление")

        elif path == 2:  # эмоции
            await show_category_practices(query, ctx, "🔥 Сильные эмоции")

        elif path == 3:  # мягкое движение
            await show_category_practices(query, ctx, "🫧 Мягкое движение")

        elif path == 4:  # дыхание
            await show_category_practices(query, ctx, "💨 Дыхание и восстановление")

        elif path == 5:  # о BodyWave
            await query.edit_message_text(tx(ctx, "about"), parse_mode="Markdown", reply_markup=paths_kb(ctx))

    # ── Direct practice from category ──
    elif data.startswith("catprac_"):
        prac_id = data[8:]
        practice = next((p for p in all_practices(lang(ctx)) if p["id"] == prac_id), None)
        if practice:
            ctx.user_data["practice"] = practice
            ctx.user_data["step"] = 0
            await show_practice_choice(query, ctx, practice=practice)

    # ── Hint (quick emotion) ──
    elif data.startswith("hint_"):
        emotion = data[5:]
        ctx.user_data["emotion"] = emotion
        ctx.user_data["awaiting_text"] = False
        await show_body_picker(query, ctx)

    # ── Emotion selected ──
    elif data.startswith("emo_"):
        emotion = data[4:]
        ctx.user_data["emotion"] = emotion
        await show_body_picker(query, ctx)

    # ── Body area selected ──
    elif data.startswith("body_"):
        idx = int(data.split("_")[1])
        areas = tx(ctx, "body_areas")
        ctx.user_data["body_area"] = areas[idx]
        await show_time_picker(query, ctx)

    # ── Topic selected ──
    elif data.startswith("topic_"):
        idx = int(data.split("_")[1])
        topics = tx(ctx, "topics")
        ctx.user_data["topic"] = topics[idx]
        await show_time_picker(query, ctx)

    # ── Time selected ──
    elif data.startswith("time_"):
        idx = int(data.split("_")[1])
        times = tx(ctx, "times")
        ctx.user_data["time"] = times[idx]
        await show_practice_choice(query, ctx)

    # ── Start practice ──
    elif data.startswith("start_"):
        prac_id = data[6:]
        l = lang(ctx)
        practice = next((p for p in all_practices(l) if p["id"] == prac_id), None)
        if practice:
            ctx.user_data["practice"] = practice
            ctx.user_data["step"] = 0
            await show_step(query, ctx)

    # ── Start practice in voice mode ──
    elif data.startswith("voice_start_"):
        prac_id = data[12:]
        l = lang(ctx)
        practice = next((p for p in all_practices(l) if p["id"] == prac_id), None)
        if practice:
            ctx.user_data["voice_mode"] = True
            ctx.user_data["practice"] = practice
            ctx.user_data["step"] = 0
            await send_continuous_practice(query, ctx, practice)

    # ── Next step ──
    elif data == "next_step":
        ctx.user_data["step"] = ctx.user_data.get("step", 0) + 1
        await show_step(query, ctx)

    # ── Toggle voice/text mode ──
    elif data == "toggle_voice":
        practice = ctx.user_data.get("practice")
        if practice:
            ctx.user_data["voice_mode"] = True
            await send_continuous_practice(query, ctx, practice)

    # ── After practice ──
    elif data.startswith("after_"):
        idx = int(data.split("_")[1])
        text = tx(ctx, "diary_saved")
        restart_kb = kb([(tx(ctx, "again_btn"), "restart")], cols=1)
        await query.edit_message_text(text, parse_mode="Markdown", reply_markup=restart_kb)

    # ── Restart ──
    elif data == "restart":
        ctx.user_data.pop("practice", None)
        ctx.user_data.pop("step", None)
        ctx.user_data.pop("emotion", None)
        ctx.user_data.pop("body_area", None)
        ctx.user_data.pop("quality", None)
        ctx.user_data.pop("topic", None)
        ctx.user_data.pop("time", None)
        await query.edit_message_text(
            welcome_text(ctx),
            parse_mode="Markdown",
            reply_markup=paths_kb(ctx)
        )

